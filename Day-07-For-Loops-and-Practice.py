# For Loop

# Print Numbers
for i in range(1, 11):
    print(i)

# Print Even Numbers
for i in range(2, 21, 2):
    print(i)

# Print Table of 5
for i in range(1, 11):
    print("5 x", i, "=", 5 * i)

# Print Characters
name = "Kazim"

for ch in name:
    print(ch)

# Sum of Numbers
sum = 0

for i in range(1, 6):
    sum += i

print("Sum =", sum)