# Chapter 2 - Variables and Data Types

# Variables

name = "Kazim"
age = 18
height = 5.8
student = True

print(name)
print(age)
print(height)
print(student)

# Data Types

print(type(name))
print(type(age))
print(type(height))
print(type(student))

# Taking Input

user_name = input("Enter your name: ")
user_age = int(input("Enter your age: "))

print("Name:", user_name)
print("Age:", user_age)

# Arithmetic Operators

a = 15
b = 5

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

# Expressions

result = (a + b) * 2
print(result)