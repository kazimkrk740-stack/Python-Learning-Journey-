#  Take diameter as input and calculate the area of a circle.

Diameter = float(input("Enter Diameter: "))
print("Diameter =",Diameter)

# Radius formula
print("  Radius formula")
Radius = Diameter/2
print("Radius = ",Radius)


print(Radius)

r=Radius
print("r= ",Radius)
π=3.14
print("π= ",π)


# Area formula 
print("   Area formula")
Area = π * r**2
print("Area = ",Area)


print("Area of circle",Area)
