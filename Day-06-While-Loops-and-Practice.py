# While Loop

num = 3

while num <= 30:
    print(num)
    num += 3

print("Program Over")

# Sum of Numbers

n = 5
sum = 0

while n >= 1:
    sum += n
    n -= 1

print("Sum =", sum)

# Countdown

num = 10

while num >= 1:
    print(num)
    num -= 1

print("Program Over")

# Even Numbers

num = 1

while num <= 50:
    if num % 2 == 0:
        print(num)

    num += 1